import { apiGet, apiPost } from '../api.js';

export default {
  name: 'abis_generate_report',
  description: 'Generate a natural language report from ABIS. Types: daily_summary, drift_alert, migration_report, compliance_doc (EU AI Act), investor_brief. Reports are generated by the ABIS Mouth organ (Groq Llama 3.1 8B) on Railway. Falls back to client-side generation if backend unavailable.',
  inputSchema: {
    type: 'object',
    properties: {
      report_type: {
        type: 'string',
        enum: ['daily_summary', 'drift_alert', 'migration_report', 'compliance_doc', 'investor_brief'],
        description: 'Which report to generate.',
      },
      model: {
        type: 'string',
        description: 'Optional: generate report for a specific model. Default: all models.',
      },
    },
    required: ['report_type'],
  },

  async execute(args) {
    const reportType = args.report_type;
    const model = args.model || 'gpt-4o';

    // Try backend Mouth organ first (Groq LLM-powered NLG)
    const backendReport = await apiPost('/report/generate', {
      model,
      report_type: reportType,
    });

    if (backendReport && backendReport.report) {
      const lines = [
        `ABIS ${reportType.toUpperCase().replace(/_/g, ' ')}`,
        '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
        `Model: ${model} | Generated: ${new Date().toISOString().substring(0, 10)}`,
        `Status: ${backendReport.overall_status || 'N/A'}`,
        '',
        backendReport.report,
        '',
        '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
        'Generated by ABIS Mouth organ (Groq Llama 3.1 8B)',
      ];
      return { content: [{ type: 'text', text: lines.join('\n') }] };
    }

    // Fallback: build report from aggregate data
    const data = await apiGet('/aggregate');
    if (!data) {
      return { content: [{ type: 'text', text: 'ABIS: Cannot generate report — Railway API offline.' }] };
    }

    const benchmarks = data.benchmarks || [];
    const latest = benchmarks.length > 0
      ? benchmarks.reduce((a, b) => (b.total_calls > a.total_calls ? b : a))
      : null;

    let report = '';

    if (reportType === 'daily_summary') {
      report = buildDailySummary(latest, benchmarks);
    } else if (reportType === 'drift_alert') {
      report = buildDriftAlert(latest);
    } else if (reportType === 'investor_brief') {
      report = buildInvestorBrief(latest, benchmarks);
    } else if (reportType === 'migration_report') {
      report = buildMigrationReport(latest);
    } else if (reportType === 'compliance_doc') {
      report = buildComplianceDoc(latest, benchmarks);
    } else {
      report = `Report type "${reportType}" — generating from available benchmark data.\n\n` + buildDailySummary(latest, benchmarks);
    }

    return { content: [{ type: 'text', text: report }] };
  }
};

function buildDailySummary(latest, all) {
  const lines = [
    'ABIS DAILY SUMMARY',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `Generated: ${new Date().toISOString().substring(0, 10)}`,
    `Total benchmark runs available: ${all.length}`,
    '',
  ];

  if (!latest || !latest.models) {
    lines.push('No benchmark data available. Run /benchmark/run to generate data.');
    return lines.join('\n');
  }

  lines.push(`Latest run: ${latest.date} (${latest.total_calls} calls)`);
  lines.push('');
  latest.models.forEach(m => {
    const icon = (m.avg_drift || 0) > 0.65 ? '🔴 ALERT' : (m.avg_drift || 0) > 0.40 ? '🟡 WATCH' : '🟢 STABLE';
    const corrections = `${m.corrections_success || 0}/${m.drifts_detected || 0} corrected`;
    lines.push(`  ${m.model}: ${(m.avg_drift || 0).toFixed(3)} avg drift — ${icon} (${corrections})`);
  });

  return lines.join('\n');
}

function buildDriftAlert(latest) {
  if (!latest || !latest.models) return 'No drift data available for alert report.';
  const alerts = latest.models.filter(m => (m.avg_drift || 0) > 0.65);
  if (alerts.length === 0) return 'ABIS DRIFT ALERT: No models currently exceeding 0.65 threshold. All clear.';

  const lines = ['⚠️ ABIS DRIFT ALERT', '━━━━━━━━━━━━━━━━━━━━━', ''];
  alerts.forEach(m => {
    lines.push(`🔴 ${m.model}: ${(m.avg_drift || 0).toFixed(3)} drift (threshold: 0.65)`);
    lines.push(`   Range: ${(m.min_drift || 0).toFixed(3)} – ${(m.max_drift || 0).toFixed(3)} | Drifts detected: ${m.drifts_detected}`);
    lines.push(`   Corrections: ${m.corrections_success || 0}/${m.drifts_detected || 0} successful`);
  });
  return lines.join('\n');
}

