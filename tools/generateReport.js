import { apiGet } from '../api.js';

export default {
  name: 'abis_generate_report',
  description: 'Generate a natural language report from ABIS. Types: daily_summary, drift_alert, migration_comparison, eu_ai_act_compliance, investor_brief. Reports are generated by the ABIS Mouth organ (Groq Llama 3.1 8B) on Railway.',
  inputSchema: {
    type: 'object',
    properties: {
      report_type: {
        type: 'string',
        enum: ['daily_summary', 'drift_alert', 'migration_comparison', 'eu_ai_act_compliance', 'investor_brief'],
        description: 'Which report to generate.',
      },
    },
    required: ['report_type'],
  },

  async execute(args) {
    // The Railway API may have report endpoints — try common patterns
    const data = await apiGet(`/aggregate`);
    if (!data) {
      return { content: [{ type: 'text', text: 'ABIS: Cannot generate report — Railway API offline.' }] };
    }

    // Build report from aggregate data since /report/{type} may not exist
    const type = args.report_type;
    const benchmarks = data.benchmarks || [];
    const latest = benchmarks.length > 0
      ? benchmarks.reduce((a, b) => (b.total_calls > a.total_calls ? b : a))
      : null;

    let report = '';

    if (type === 'daily_summary') {
      report = buildDailySummary(latest, benchmarks);
    } else if (type === 'drift_alert') {
      report = buildDriftAlert(latest);
    } else if (type === 'investor_brief') {
      report = buildInvestorBrief(latest, benchmarks);
    } else {
      report = `Report type "${type}" — generating from available benchmark data.\n\n` + buildDailySummary(latest, benchmarks);
    }

    return { content: [{ type: 'text', text: report }] };
  }
};

function buildDailySummary(latest, all) {
  const lines = [
    'ABIS DAILY SUMMARY',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `Generated: ${new Date().toISOString().substring(0, 10)}`,
    `Total benchmark runs available: ${all.length}`,
    '',
  ];

  if (!latest || !latest.models) {
    lines.push('No benchmark data available. Run /benchmark/run to generate data.');
    return lines.join('\n');
  }

  lines.push(`Latest run: ${latest.date} (${latest.total_calls} calls)`);
  lines.push('');
  latest.models.forEach(m => {
    const icon = (m.avg_drift || 0) > 0.65 ? '🔴 ALERT' : (m.avg_drift || 0) > 0.40 ? '🟡 WATCH' : '🟢 STABLE';
    lines.push(`  ${m.model}: ${(m.avg_drift || 0).toFixed(3)} avg drift — ${icon}`);
  });

  return lines.join('\n');
}

function buildDriftAlert(latest) {
  if (!latest || !latest.models) return 'No drift data available for alert report.';
  const alerts = latest.models.filter(m => (m.avg_drift || 0) > 0.65);
  if (alerts.length === 0) return 'ABIS DRIFT ALERT: No models currently exceeding 0.65 threshold. All clear.';

  const lines = ['⚠️ ABIS DRIFT ALERT', '━━━━━━━━━━━━━━━━━━━━━', ''];
  alerts.forEach(m => {
    lines.push(`🔴 ${m.model}: ${(m.avg_drift || 0).toFixed(3)} drift (threshold: 0.65)`);
    lines.push(`   Range: ${(m.min_drift || 0).toFixed(3)} – ${(m.max_drift || 0).toFixed(3)} | Drifts detected: ${m.drifts_detected}`);
  });
  return lines.join('\n');
}

function buildInvestorBrief(latest, all) {
  const lines = [
    'ABIS INVESTOR BRIEF',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    'CIJ Labs — Adaptive Behavioral Intelligence System',
    'Patent: GB2521226.7',
    '',
    `Total benchmark runs: ${all.length}`,
    `Models monitored: ${latest?.models?.length || 8}`,
    `Measurement dimensions: 1,544 (272D behavioral + derived)`,
    '',
    'ABIS provides deterministic behavioral measurement for LLMs,',
    'detecting silent model changes before they impact production systems.',
  ];
  return lines.join('\n');
}
