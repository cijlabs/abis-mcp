function buildMigrationReport(latest) {
  if (!latest || !latest.models || latest.models.length < 2) {
    return 'ABIS MIGRATION REPORT: Insufficient model data for comparison. Need at least 2 models.';
  }

  const sorted = [...latest.models].sort((a, b) => (a.avg_drift || 1) - (b.avg_drift || 1));
  const lines = [
    'ABIS MIGRATION REPORT',
    '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━',
    `Generated: ${new Date().toISOString().substring(0, 10)}`,
    '',
    'MODELS RANKED BY BEHAVIORAL STABILITY:',
    '',
  ];

  sorted.forEach((m, i) => {
    const icon = (m.avg_drift || 0) > 0.65 ? '🔴' : (m.avg_drift || 0) > 0.40 ? '🟡' : '🟢';
    const corrRate = m.drifts_detected > 0
      ? `${((m.corrections_success || 0) / m.drifts_detected * 100).toFixed(0)}%`
      : 'N/A';
    lines.push(`  ${i + 1}. ${icon} ${m.model}`);
    lines.push(`     Drift: ${(m.avg_drift || 0).toFixed(3)} [${(m.min_drift || 0).toFixed(3)}-${(m.max_drift || 0).toFixed(3)}]`);
    lines.push(`     Correction rate: ${corrRate} | Prompts: ${m.prompts_run}`);
    lines.push('');
  });

  lines.push('RECOMMENDATION:');
  const best = sorted[0];
  const worst = sorted[sorted.length - 1];
  lines.push(`  Most stable: ${best.model} (${(best.avg_drift || 0).toFixed(3)} drift)`);
  lines.push(`  Least stable: ${worst.model} (${(worst.avg_drift || 0).toFixed(3)} drift)`);

  return lines.join('\n');
}

